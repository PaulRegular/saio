root <- "."
path <- file.path(root, "discovery", "candidates.csv")
register_lines <- readLines(path, encoding = "UTF-8", warn = FALSE)
register <- read.csv(path, stringsAsFactors = FALSE, na.strings = c("", "NA"),
  check.names = FALSE)

clean_value <- function(x) {
  if (is.null(x) || length(x) == 0L || is.na(x) || !nzchar(x)) NA_character_ else x
}

add <- function(id, unit, stock_id, scientific, stock, area, year, source,
  reason, notes = "", catch = "", survey = "", weights = "", maturity = "",
  mortality = "", timing = "", output = "", eligibility = "ineligible",
  match_status = "new", import_status = "not_started", dfo_ref = NULL) {
  matched_stock_id <- NA_character_
  if (!is.null(dfo_ref)) {
    i <- match(dfo_ref, register$candidate_id)
    if (is.na(i)) stop("Missing DFO crosswalk row: ", dfo_ref)
    ref <- register[i, , drop = FALSE]
    if (is.na(ref$candidate_unit_id) || !nzchar(ref$candidate_unit_id)) {
      stop("DFO crosswalk has no candidate_unit_id: ", dfo_ref)
    }
    unit <- ref$candidate_unit_id
    match_status <- ref$match_status
    matched_stock_id <- clean_value(ref$matched_stock_id)
    import_status <- ref$import_status
  }

  data.frame(
    candidate_id = id,
    candidate_unit_id = clean_value(unit),
    organization = "NAFO",
    official_stock_id = stock_id,
    scientific_name = scientific,
    stock_name = stock,
    assessment_area = area,
    inventory_assessment_year = as.integer(year),
    inventory_url = "https://www.nafo.int/Science/Science-Advice/Stock-advice",
    retrieved_on = "2026-11-04",
    matched_stock_id = matched_stock_id,
    match_status = match_status,
    screening_status = "screened",
    eligibility = eligibility,
    import_status = import_status,
    catch_age_evidence = catch,
    survey_age_evidence = survey,
    weights_evidence = weights,
    maturity_evidence = maturity,
    mortality_evidence = mortality,
    timing_evidence = timing,
    output_evidence = output,
    detailed_source_url = source,
    review_date = "2026-11-04",
    decision_reason = reason,
    notes = notes,
    stringsAsFactors = FALSE
  )
}

